/**
 * Install Agents MD command - Generate and append CLI usage instructions to AGENTS.md
 */

import { readFile, writeFile, access } from "fs/promises";
import { resolve, join } from "path";
import type { CommandContext } from "../cli/types.js";
import { Command } from "commander";

interface InstallAgentsMdOptions {
  file?: string;
  workingDir?: string;
  force?: boolean;
}

/**
 * Check if a command exists in the Commander.js program
 */
function commandExists(program: Command, commandName: string): boolean {
  try {
    const commands = program.commands || [];
    return commands.some((cmd) => {
      const name = typeof cmd.name === "function" ? cmd.name() : cmd.name;
      return name === commandName;
    });
  } catch {
    return false;
  }
}

/**
 * Check if a command has a specific option
 */
function commandHasOption(
  program: Command,
  commandName: string,
  optionName: string
): boolean {
  try {
    const commands = program.commands || [];
    const cmd = commands.find((cmd) => {
      const name = typeof cmd.name === "function" ? cmd.name() : cmd.name;
      return name === commandName;
    });

    if (!cmd) return false;

    // Check if option exists by looking at options
    const options = (cmd as any).options || [];
    return options.some((opt: any) => {
      const long = opt.long || "";
      const short = opt.short || "";
      // Check for exact match or if option name appears in the option string
      // e.g., "--plan <file>" should match "plan"
      return (
        long === `--${optionName}` ||
        short === `-${optionName}` ||
        long.includes(`--${optionName}`) ||
        long.includes(`<${optionName}>`) ||
        long.toLowerCase().includes(optionName.toLowerCase())
      );
    });
  } catch {
    return false;
  }
}

