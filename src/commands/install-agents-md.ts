/**
 * Check if launch --plan command instructions already exist in content
 */
function hasLaunchCommandInstructions(content: string): boolean {
  // Simple check: look for "launch --plan" pattern
  return content.includes("launch --plan");
}

export async function executeInstallAgentsMd(
  context: CommandContext,
  options: InstallAgentsMdOptions
): Promise<void> {
  const { workingDir } = context;
  const targetFile = options.file || "AGENTS.md";
  const workingDirectory = options.workingDir || workingDir;

  try {
    // Resolve the target file path
    const filePath = resolve(workingDirectory, targetFile);

    // Check if file exists
    let fileExists = false;
    try {
      await access(filePath);
      fileExists = true;
    } catch {
      fileExists = false;
    }

    // Read existing content or start with empty string
    let existingContent = "";
    if (fileExists) {
      existingContent = await readFile(filePath, "utf-8");
    }

    // Check if launch command instructions already exist (unless --force is used)
    if (!options.force && hasLaunchCommandInstructions(existingContent)) {
      console.log(`✓ ${targetFile} already contains CLI usage instructions`);
      console.log(`  Skipping installation to prevent duplicates.`);
      console.log(`  Use --force to overwrite existing instructions.`);
      return;
    }

    // Create a temporary Commander.js program to check commands
    const { Command } = await import("commander");
    const program = new Command();
    const { registerCommands } = await import("./index.js");
    registerCommands(program, context);

    // Generate new instructions
    const newInstructions = generateInstructions(program);

    // Check if section already exists (even without launch instructions)
    const sectionMarker = "## CLI Usage for AI Agents";
    if (existingContent.includes(sectionMarker)) {
      // Find the section and replace it
      const sectionStart = existingContent.indexOf(sectionMarker);
      const nextSectionMatch = existingContent
        .slice(sectionStart + sectionMarker.length)
        .match(/^## /m);
      const sectionEnd = nextSectionMatch
        ? sectionStart +
          sectionMarker.length +
          existingContent
            .slice(sectionStart + sectionMarker.length)
            .indexOf(nextSectionMatch[0])
        : existingContent.length;

      const beforeSection = existingContent.slice(0, sectionStart);
      const afterSection = existingContent.slice(sectionEnd);

      // Reconstruct content with updated section
      const updatedContent =
        beforeSection +
        newInstructions +
        (afterSection ? "\n" + afterSection : "");

      await writeFile(filePath, updatedContent, "utf-8");
      console.log(`✓ Updated ${targetFile} with latest CLI usage instructions`);
    } else {
      // Append new section
      const updatedContent =
        existingContent +
        (existingContent && !existingContent.endsWith("\n") ? "\n" : "") +
        "\n" +
        newInstructions;

      await writeFile(filePath, updatedContent, "utf-8");
      console.log(`✓ Added CLI usage instructions to ${targetFile}`);
    }
  } catch (error) {
    if (error instanceof Error) {
      console.error(`Error: ${error.message}`);
    } else {
      console.error("Error: Failed to install agents.md instructions");
    }
    process.exit(1);
  }
}
